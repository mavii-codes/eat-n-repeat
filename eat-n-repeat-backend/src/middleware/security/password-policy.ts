const COMMON_PASSWORD_SET = new Set(COMMON_PASSWORDS);
const MIN_LENGTH = 8;

/**
 * Returns a human-readable error message when `pw` violates the policy,
 * otherwise null.
 */
export function assertPasswordPolicy(pw: string): string | null {
  if (typeof pw !== "string" || pw.length < MIN_LENGTH) {
    return "Password must be at least 8 characters.";
  }
  if (COMMON_PASSWORD_SET.has(pw.trim().toLowerCase())) {
    return "That password is too common. Choose a different one.";
  }
  return null;
}
