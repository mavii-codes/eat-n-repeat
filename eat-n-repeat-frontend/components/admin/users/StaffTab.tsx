"use client";

/* User Management — Staff sub-page. Create / Edit / Disable / Enable /
   Reset password actions against /api/admin/users/staff/* plus the
   admin-only /api/staff create & temp-password endpoints. Backend 409
   messages (last admin, open shift, duplicate email/username) stay open
   inside their dialogs, word for word. */

import { useEffect, useMemo, useState } from "react";
import toast from "react-hot-toast";
import { Check, Copy, KeyRound, Pencil, Power, UserPlus, Users } from "lucide-react";
import { useConfirm } from "@/components/shared/ConfirmDialog";
import { AdminModal } from "@/components/admin/AdminModal";
import {
  AdminButton,
  AdminField,
  AdminInput,
  AdminPanel,
  AdminSelect,
} from "@/components/admin/AdminForm";
import { useAuth } from "@/context/AuthContext";
import {
  createStaffPage,
  fetchStaffPage,
  fetchTempPassword,
  staffAction,
  updateStaffPage,
  type ActionResult,
} from "./api";
import { relativeLastLogin, shortDate } from "./format";
import { useUserList } from "./use-user-list";
import type { StaffRow, UserListQuery } from "./types";
import {
  copyText,
  EmptyState,
  ErrorBanner,
  Pagination,
  RefreshButton,
  RoleBadge,
  SearchInput,
  OpenShiftChip,
  SortDirButton,
  StatusPill,
  TableSkeleton,
  ToolbarSelect,
} from "./ui";

const LIMIT = 20;

export default function StaffTab() {
  const { user } = useAuth();
  const currentUserId = user?.id;
  const { confirm, confirmAction } = useConfirm();

  const [applied, setApplied] = useState({
    page: 1,
    search: "",
    role: "all",
    status: "all",
    sort: "name",
    dir: "asc" as "asc" | "desc",
  });

  const query = useMemo<UserListQuery>(
    () => ({
      page: applied.page,
      limit: LIMIT,
      search: applied.search,
      role: applied.role,
      status: applied.status,
      sort: applied.sort,
      dir: applied.dir,
    }),
    [applied],
  );

  const { data, loading, error, refresh } = useUserList<StaffRow>(
    fetchStaffPage,
    query,
  );
  const rows = data?.rows ?? [];
  const total = data?.total ?? 0;

  // A filter or search change restarts from page 1; pagination alone moves.
  function update(patch: Partial<typeof applied>) {
    setApplied((prev) => ({ ...prev, page: 1, ...patch }));
  }
  function handlePage(next: number) {
    setApplied((prev) => ({ ...prev, page: Math.max(1, next) }));
  }

  /* ── Actions ────────────────────────────────────────────────────────── */

  const [resettingId, setResettingId] = useState<string | null>(null);
  const [resetResult, setResetResult] = useState<{
    name: string;
    tempPassword: string;
  } | null>(null);

  /* ── Create / Edit ──────────────────────────────────────────────────── */

  type StaffFormState = {
    name: string;
    username: string;
    email: string;
    role: string;
    status: string;
    password: string;
  };

  const emptyForm: StaffFormState = {
    name: "",
    username: "",
    email: "",
    role: "staff",
    status: "active",
    password: "",
  };

  const [formOpen, setFormOpen] = useState(false);
  const [editingId, setEditingId] = useState<string | null>(null);
  const [form, setForm] = useState<StaffFormState>(emptyForm);
  const [formError, setFormError] = useState<string | null>(null);
  const [formBusy, setFormBusy] = useState(false);
  // Create mode only: the initial password is either typed by the admin or
  // generated by the backend (same friendly format the reset flow uses).
  const [generatedPassword, setGeneratedPassword] = useState<string | null>(null);
  const [generating, setGenerating] = useState(false);

  function openCreate() {
    setForm(emptyForm);
    setEditingId(null);
    setGeneratedPassword(null);
    setFormError(null);
    setFormOpen(true);
  }

  function openEdit(row: StaffRow) {
    setForm({
      name: row.name || "",
      username: row.username || "",
      email: row.email || "",
      role: row.role || "staff",
      status: (row.status || "active").toLowerCase(),
      password: "",
    });
    setEditingId(row.id);
    setGeneratedPassword(null);
    setFormError(null);
    setFormOpen(true);
  }

  // Fresh dialog state whenever it opens (mirrors FlagCustomerModal).
  useEffect(() => {
    if (formOpen) {
      setFormError(null);
      setFormBusy(false);
    }
  }, [formOpen]);

  async function handleGeneratePassword() {
    if (generating) return;
    setGenerating(true);
    const result = await fetchTempPassword();
    setGenerating(false);
    if (result.ok) {
      setGeneratedPassword(result.tempPassword);
      setForm((prev) => ({ ...prev, password: result.tempPassword }));
      setFormError(null);
    } else {
      setFormError(result.message);
    }
  }

  async function handleFormSubmit() {
    if (formBusy) return;
    const name = form.name.trim();
    const username = form.username.trim();
    const email = form.email.trim();
    if (!name || !username || !email) {
      setFormError("Name, username, and email are all required.");
      return;
    }
    // Admin creation is blocked by the backend (403); don't offer the role.
    if (!editingId && !generatedPassword && form.password.trim().length < 8) {
      setFormError("Password must be at least 8 characters — type one or use Generate.");
      return;
    }
    setFormBusy(true);
    setFormError(null);
    const input = {
      name,
      username,
      email,
      role: form.role,
      status: form.status,
      ...(!editingId && form.password.trim() ? { password: form.password.trim() } : {}),
    };
    const result: ActionResult = editingId
      ? await updateStaffPage(editingId, input)
      : await createStaffPage(input);
    setFormBusy(false);
    if (result.ok) {
      toast.success(
        editingId
          ? `${name} updated.`
          : `${name} added. Give them the password shown to sign in.`,
      );
      setFormOpen(false);
      refresh();
    } else {
      // 409 / 400 / 403 messages surface verbatim; the dialog stays open.
      setFormError(result.message);
    }
  }

  async function handleDisable(row: StaffRow) {
    if (currentUserId && row.id === currentUserId) {
      toast.error("You can't disable your own account while signed in.");
      return;
    }
    const confirmed = await confirmAction({
      title: `Disable ${row.name}?`,
      message:
        "This blocks sign-in and revokes their active sessions immediately." +
        (row.hasOpenShift ? " They currently have an open shift." : ""),
      variant: "danger",
      confirmLabel: "Disable",
      workingLabel: "Disabling",
      action: async () => {
        const result = await staffAction(row.id, "disable");
        if (!result.ok) return result.message;
        return null;
      },
    });
    if (confirmed) {
      toast.success(`${row.name} can no longer sign in.`);
      refresh();
    }
  }

  async function handleEnable(row: StaffRow) {
    const confirmed = await confirmAction({
      title: `Enable ${row.name}?`,
      message: "They will regain access and can sign in again.",
      variant: "info",
      confirmLabel: "Enable",
      workingLabel: "Enabling",
      action: async () => {
        const result = await staffAction(row.id, "enable");
        return result.ok ? null : result.message;
      },
    });
    if (confirmed) {
      toast.success(`${row.name} can sign in again.`);
      refresh();
    }
  }

  async function handleResetPassword(row: StaffRow) {
    const confirmed = await confirm({
      title: "Reset password?",
      message: `Generate a new temporary password for ${row.name}? Their current password stops working right away.`,
      variant: "warning",
      confirmLabel: "Reset password",
    });
    if (!confirmed) return;
    setResettingId(row.id);
    const result: ActionResult = await staffAction(row.id, "reset-password");
    setResettingId(null);
    if (result.ok && result.tempPassword) {
      setResetResult({ name: row.name, tempPassword: result.tempPassword });
      refresh();
    } else if (!result.ok) {
      toast.error(result.message);
    } else {
      toast.error("No temporary password came back from the server. Try again.");
    }
  }

  /* ── Render pieces ──────────────────────────────────────────────────── */

  const actionButtons = (row: StaffRow, align: "right" | "left") => {
    const alignClass = align === "right" ? "justify-end" : "";
    const isActive = (row.status || "active").toLowerCase() === "active";
    const editButton = (
      <ActionButton
        tone="muted"
        icon={<Pencil className="h-3.5 w-3.5" />}
        label="Edit"
        onClick={() => openEdit(row)}
      />
    );
    if (!isActive) {
      // Disabled rows show Edit + Enable only. There is deliberately no delete.
      return (
        <div className={`flex ${alignClass} gap-1.5`}>
          {editButton}
          <ActionButton
            tone="green"
            icon={<Power className="h-3.5 w-3.5" />}
            label="Enable"
            onClick={() => handleEnable(row)}
          />
        </div>
      );
    }
    return (
      <div className={`flex ${alignClass} gap-1.5`}>
        {editButton}
        <ActionButton
          tone="muted"
          icon={<KeyRound className="h-3.5 w-3.5" />}
          label={resettingId === row.id ? "Generating…" : "Reset password"}
          disabled={resettingId === row.id}
          onClick={() => handleResetPassword(row)}
        />
        <ActionButton
          tone="red"
          icon={<Power className="h-3.5 w-3.5" />}
          label="Disable"
          onClick={() => handleDisable(row)}
        />
      </div>
    );
  };

  return (
    <AdminPanel
      title="Staff Directory"
      subtitle={
        data ? `${total} staff account${total === 1 ? "" : "s"}` : undefined
      }
      action={
        <div className="flex items-center gap-2">
          <AdminButton onClick={openCreate} className="flex items-center gap-1.5">
            <UserPlus className="h-4 w-4" />
            Add staff
          </AdminButton>
          <RefreshButton busy={loading} onClick={refresh} />
        </div>
      }
    >
      {/* Toolbar */}
      <div className="flex flex-col gap-3 px-4 py-4 sm:flex-row sm:items-center sm:flex-wrap sm:justify-between">
        <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:flex-wrap">
          <SearchInput
            onCommit={(value) => update({ search: value })}
            placeholder="Search staff…"
          />
          <ToolbarSelect
            value={applied.role}
            onChange={(value) => update({ role: value })}
          >
            <option value="all">All Roles</option>
            <option value="admin">Admin</option>
            <option value="head_staff">Head Staff</option>
            <option value="staff">Staff</option>
            <option value="delivery_rider">Delivery Rider</option>
          </ToolbarSelect>
          <ToolbarSelect
            value={applied.status}
            onChange={(value) => update({ status: value })}
          >
            <option value="all">All Status</option>
            <option value="active">Active</option>
            <option value="disabled">Disabled</option>
          </ToolbarSelect>
          <ToolbarSelect
            value={applied.sort}
            onChange={(value) => update({ sort: value })}
          >
            <option value="name">Sort: Name</option>
            <option value="createdAt">Sort: Date created</option>
            <option value="lastLoginAt">Sort: Last login</option>
          </ToolbarSelect>
          <SortDirButton
            dir={applied.dir}
            onToggle={() =>
              update({ dir: applied.dir === "asc" ? "desc" : "asc" })
            }
          />
        </div>
      </div>

      {error && <ErrorBanner message={error} onRetry={refresh} />}

      {/* Loading skeleton (first load) */}
      {loading && rows.length === 0 && <TableSkeleton rows={6} />}

      {/* Empty state */}
      {!loading && !error && rows.length === 0 && (
        <EmptyState
          icon={<Users className="h-5 w-5" />}
          title="No staff found"
          hint="Try a different search or clear the filters."
        />
      )}

      {/* Desktop table */}
      {rows.length > 0 && (
        <div
          className={`hidden md:block overflow-x-auto px-3 pb-2 ${
            loading ? "pointer-events-none opacity-60 transition-opacity" : ""
          }`}
        >
          <table className="w-full min-w-[860px] text-left text-sm">
            <thead>
              <tr className="admin-table-head text-stone-500 border-b border-stone-200">
                <th className="rounded-tl-xl px-4 py-3 font-medium">Staff</th>
                <th className="px-4 py-3 font-medium">Role</th>
                <th className="px-4 py-3 font-medium">Status</th>
                <th className="px-4 py-3 font-medium">Last login</th>
                <th className="px-4 py-3 font-medium">Created</th>
                <th className="rounded-tr-xl px-4 py-3 font-medium text-right">
                  Actions
                </th>
              </tr>
            </thead>
            <tbody>
              {rows.map((row, i) => (
                <tr
                  key={row.id}
                  className={`border-b border-stone-100 last:border-0 hover:bg-stone-50/50 transition-colors ${
                    i < 10 ? "animate-in fade-in duration-300" : ""
                  }`}
                  style={i < 10 ? { animationDelay: `${i * 24}ms` } : undefined}
                >
                  <td className="px-4 py-3">
                    <div className="flex flex-col">
                      <span className="font-semibold text-[#800000]">{row.name}</span>
                      <span className="text-xs text-stone-400">{row.email}</span>
                      <span className="text-xs font-mono text-stone-400">
                        @{row.username}
                      </span>
                    </div>
                  </td>
                  <td className="px-4 py-3">
                    <RoleBadge role={row.role} />
                  </td>
                  <td className="px-4 py-3">
                    <div className="flex items-center gap-1.5">
                      <StatusPill status={row.status} />
                      {row.hasOpenShift && <OpenShiftChip />}
                    </div>
                  </td>
                  <td className="px-4 py-3 text-xs text-stone-500 font-medium">
                    {relativeLastLogin(row.lastLoginAt)}
                  </td>
                  <td className="px-4 py-3 text-xs text-stone-500 font-medium">
                    {shortDate(row.createdAt)}
                  </td>
                  <td className="px-4 py-3 text-right">{actionButtons(row, "right")}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {/* Mobile cards */}
      {rows.length > 0 && (
        <div
          className={`md:hidden flex flex-col gap-3 p-3 ${
            loading ? "pointer-events-none opacity-60 transition-opacity" : ""
          }`}
        >
          {rows.map((row) => (
            <div
              key={row.id}
              className="bg-white border border-stone-100 rounded-xl p-4 shadow-sm"
            >
              <div className="flex justify-between items-start gap-3">
                <div>
                  <h4 className="font-semibold text-[#800000] leading-tight">
                    {row.name}
                  </h4>
                  <p className="text-xs font-mono text-stone-500 mt-0.5">
                    @{row.username}
                  </p>
                </div>
                <div className="flex flex-col items-end gap-1">
                  <StatusPill status={row.status} />
                  {row.hasOpenShift && <OpenShiftChip />}
                </div>
              </div>

              <div className="grid grid-cols-2 gap-y-2 gap-x-4 text-sm mt-3">
                <div>
                  <p className="text-[10px] text-stone-400 uppercase tracking-wider font-semibold mb-1">
                    Role
                  </p>
                  <RoleBadge role={row.role} />
                </div>
                <div>
                  <p className="text-[10px] text-stone-400 uppercase tracking-wider font-semibold mb-1">
                    Last login
                  </p>
                  <p className="font-medium text-stone-700 text-xs">
                    {relativeLastLogin(row.lastLoginAt)}
                  </p>
                </div>
                <div className="col-span-2 pt-2 border-t border-stone-100 flex items-center justify-between">
                  <span className="text-[10px] text-stone-400 font-medium">
                    Created {shortDate(row.createdAt)}
                  </span>
                  {actionButtons(row, "left")}
                </div>
              </div>
            </div>
          ))}
        </div>
      )}

      {rows.length > 0 && (
        <Pagination
          page={applied.page}
          limit={LIMIT}
          total={total}
          onPage={handlePage}
        />
      )}

      {/* Reset-password result modal (password shown exactly once) */}
      <AdminModal
        open={!!resetResult}
        title="Temporary password generated"
        onClose={() => setResetResult(null)}
        footer={
          <AdminButton
            variant="secondary"
            onClick={() => setResetResult(null)}
          >
            Close
          </AdminButton>
        }
      >
        {resetResult && (
          <div className="space-y-4">
            <p className="text-sm text-stone-600">
              Give this temporary password to {resetResult.name}. It is shown
              once and will not appear again.
            </p>
            <TempPasswordBox tempPassword={resetResult.tempPassword} />
            <p className="text-xs text-stone-500">
              The team member must change it at next sign-in.
            </p>
          </div>
        )}
      </AdminModal>

      {/* Create / Edit staff modal — 409s (duplicate email/username), 400s
          (password policy) and 403s (admin creation block) surface verbatim. */}
      <AdminModal
        open={formOpen}
        title={editingId ? "Edit staff member" : "Add staff member"}
        onClose={() => setFormOpen(false)}
        footer={
          <div className="flex items-center gap-3">
            <AdminButton
              variant="secondary"
              onClick={() => setFormOpen(false)}
              disabled={formBusy}
            >
              Cancel
            </AdminButton>
            <AdminButton onClick={handleFormSubmit} disabled={formBusy}>
              {formBusy
                ? "Saving…"
                : editingId
                  ? "Save changes"
                  : "Add staff member"}
            </AdminButton>
          </div>
        }
      >
        <div className="space-y-4">
          {formError && (
            <div
              role="alert"
              className="rounded-xl border border-red-200 bg-red-50 px-3 py-2.5 text-sm text-red-700"
            >
              {formError}
            </div>
          )}

          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
            <AdminField label="Full name">
              <AdminInput
                value={form.name}
                onChange={(e) => setForm((p) => ({ ...p, name: e.target.value }))}
                placeholder="e.g. Juan Dela Cruz"
                autoFocus
                disabled={formBusy}
              />
            </AdminField>
            <AdminField label="Username">
              <AdminInput
                value={form.username}
                onChange={(e) =>
                  setForm((p) => ({ ...p, username: e.target.value }))
                }
                placeholder="e.g. juan.dc"
                disabled={formBusy}
              />
            </AdminField>
          </div>

          <AdminField label="Email">
            <AdminInput
              type="email"
              value={form.email}
              onChange={(e) => setForm((p) => ({ ...p, email: e.target.value }))}
              placeholder="e.g. juan@eatnrepeat.ph"
              disabled={formBusy}
            />
          </AdminField>

          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
            <AdminField label="Role">
              <AdminSelect
                value={form.role}
                onChange={(e) => setForm((p) => ({ ...p, role: e.target.value }))}
                disabled={formBusy}
              >
                <option value="staff">Staff</option>
                <option value="head_staff">Head staff</option>
                <option value="delivery_rider">Delivery rider</option>
              </AdminSelect>
            </AdminField>
            <AdminField label="Status">
              <AdminSelect
                value={form.status}
                onChange={(e) =>
                  setForm((p) => ({ ...p, status: e.target.value }))
                }
                disabled={formBusy}
              >
                <option value="active">Active</option>
                <option value="disabled">Disabled</option>
              </AdminSelect>
            </AdminField>
          </div>

          {!editingId && (
            <AdminField label="Initial password">
              <div className="flex items-center gap-2">
                <AdminInput
                  type="text"
                  value={form.password}
                  onChange={(e) =>
                    setForm((p) => ({ ...p, password: e.target.value }))
                  }
                  placeholder="At least 8 characters, or Generate"
                  disabled={formBusy}
                />
                <AdminButton
                  variant="secondary"
                  onClick={handleGeneratePassword}
                  disabled={generating || formBusy}
                  className="shrink-0 whitespace-nowrap"
                >
                  {generating ? "Generating…" : "Generate"}
                </AdminButton>
              </div>
              <p className="mt-1.5 text-xs text-stone-500">
                Shown once here — share it with the team member for their first
                sign-in. They must change it at next sign-in.
              </p>
            </AdminField>
          )}
          {editingId && (
            <p className="text-xs text-stone-500">
              Password changes use the Reset password action, not this form.
            </p>
          )}
        </div>
      </AdminModal>
    </AdminPanel>
  );
}

function TempPasswordBox({ tempPassword }: { tempPassword: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <div className="flex items-center gap-2 rounded-xl border border-stone-200 bg-stone-50 px-3 py-2.5">
      <code className="flex-1 font-mono text-base font-bold text-[#800000] tracking-wide break-all">
        {tempPassword}
      </code>
      <button
        type="button"
        onClick={async () => {
          const ok = await copyText(tempPassword);
          if (ok) {
            setCopied(true);
            setTimeout(() => setCopied(false), 1600);
          } else {
            toast.error("Copy failed. Select the password and copy it manually.");
          }
        }}
        className="inline-flex shrink-0 items-center gap-1.5 rounded-lg border border-stone-200 bg-white px-3 py-2 text-xs font-bold text-stone-600 hover:bg-stone-100 transition-colors focus:outline-none focus:ring-2 focus:ring-[#800000]/30"
      >
        {copied ? (
          <>
            <Check className="h-3.5 w-3.5 text-green-600" />
            Copied
          </>
        ) : (
          <>
            <Copy className="h-3.5 w-3.5" />
            Copy
          </>
        )}
      </button>
    </div>
  );
}

/* Small text action button in the CrudActions style of the admin kit. */
function ActionButton({
  tone,
  icon,
  label,
  onClick,
  disabled,
}: {
  tone: "muted" | "red" | "green";
  icon: React.ReactNode;
  label: string;
  onClick: () => void;
  disabled?: boolean;
}) {
  const tones: Record<string, string> = {
    muted: "text-accent hover:bg-accent-light",
    red: "text-red-600 hover:bg-red-50",
    green: "text-green-700 hover:bg-green-50",
  };
  return (
    <button
      type="button"
      onClick={onClick}
      disabled={disabled}
      className={`inline-flex items-center gap-1.5 rounded-lg px-2.5 py-1.5 text-xs font-semibold transition-colors disabled:opacity-60 disabled:cursor-not-allowed ${tones[tone]} focus:outline-none focus:ring-2 focus:ring-[#800000]/20`}
    >
      {icon}
      {label}
    </button>
  );
}
